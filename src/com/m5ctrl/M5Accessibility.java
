package com.m5ctrl;

import android.accessibilityservice.AccessibilityService;
import android.content.Context;
import android.os.IBinder;
import android.util.Log;
import android.view.KeyEvent;
import android.view.accessibility.AccessibilityEvent;
import rikka.shizuku.Shizuku;
import android.hardware.display.IDisplayManager;
import java.io.File;
import java.io.FileOutputStream;
import java.io.InputStream;

public class M5Accessibility extends AccessibilityService {
    private static final String TAG = "M5Accessibility";
    private boolean mScreenOff = false;
    private long mMenuDownTime = 0;
    private static final int LONG_PRESS_MS = 500;

    @Override
    public void onServiceConnected() {
        super.onServiceConnected();
        Log.d(TAG, "无障碍服务已启动");
        copyAndRunDaemon();
    }

    @Override
    public boolean onKeyEvent(KeyEvent event) {
        int keyCode = event.getKeyCode();
        // 长按菜单键切换手机内置屏
        if (keyCode == KeyEvent.KEYCODE_MENU) {
            if (event.getAction() == KeyEvent.ACTION_DOWN) {
                mMenuDownTime = event.getEventTime();
            } else if (event.getAction() == KeyEvent.ACTION_UP) {
                if (event.getEventTime() - mMenuDownTime >= LONG_PRESS_MS) {
                    toggleInternalScreen();
                    return true;
                }
            }
        }
        return super.onKeyEvent(event);
    }

    private void toggleInternalScreen() {
        if (Shizuku.getVersion() < 11) {
            Log.w(TAG, "Shizuku版本不足，无法控制屏幕");
            return;
        }
        try {
            IBinder b = Shizuku.getBinder();
            IDisplayManager dm = IDisplayManager.Stub.asInterface(b);
            if (mScreenOff) {
                dm.setDisplayPowerMode(0, 2);
                mScreenOff = false;
            } else {
                dm.setDisplayPowerMode(0, 0);
                mScreenOff = true;
            }
        } catch (Exception e) {
            Log.e(TAG, "切换屏幕失败", e);
        }
    }

    private void copyAndRunDaemon() {
        try {
            File daemonFile = new File(getFilesDir(), "m5ctl");
            if (!daemonFile.exists()) {
                InputStream is = getAssets().open("m5ctl");
                FileOutputStream fos = new FileOutputStream(daemonFile);
                byte[] buf = new byte[1024];
                int len;
                while ((len = is.read(buf)) > 0) {
                    fos.write(buf, 0, len);
                }
                is.close();
                fos.close();
                daemonFile.setExecutable(true);
            }
            Runtime.getRuntime().exec(daemonFile.getAbsolutePath());
            Log.d(TAG, "守护进程已启动");
        } catch (Exception e) {
            Log.e(TAG, "启动守护进程失败", e);
        }
    }

    @Override
    public void onAccessibilityEvent(AccessibilityEvent event) {}

    @Override
    public void onInterrupt() {}
}
